    private void btnGenerarUniversoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarUniversoActionPerformed
        try {
            String textoTamano = txtTamanoUniversal.getText().trim();
            if (textoTamano.isEmpty()) {
                throw new Exception("Por favor ingrese el tamaño del Universo.");
            }

            int tamano = Integer.parseInt(textoTamano);

            // 1. Generar el universo a través de la controladora
            // (Nota: Si la elección de Vector/Lista la hace al final como mencionas,
            //  aquí puedes generarlo por defecto o esperar a cambiar el tipo en la controladora)
            control.generarUniverso(tamano, true);

            // 2. Crear la siguiente pantalla pasándole la misma Controladora
            // para mantener los datos del Universo vivo
            VentanaConfiguracionConjuntos siguientePantalla = new VentanaConfiguracionConjuntos(control);

            // 3. Hacer visible la nueva pantalla y centrarla
            siguientePantalla.setVisible(true);
            siguientePantalla.setLocationRelativeTo(null);

            // 4. Cerrar o ocultar la pantalla actual
            this.dispose();

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Debe ingresar un número entero válido.", "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Atención", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnGenerarUniversoActionPerformed

