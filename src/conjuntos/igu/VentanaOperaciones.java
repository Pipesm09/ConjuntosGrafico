    private void btnComplementoBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnComplementoBActionPerformed
        try {
            boolean esVector = comboRepresentacion.getSelectedItem().toString().contains("Vector");
            ConjuntoInterface resultado;

            if (esVector) {
                resultado = control.getConjuntoBVector().complemento(control.getUniversalActual());
            } else {
                resultado = control.getConjuntoBLista().complemento(control.getUniversalActual());
            }

            mostrarResultado("B'", resultado);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al calcular el complemento de B: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnComplementoBActionPerformed

