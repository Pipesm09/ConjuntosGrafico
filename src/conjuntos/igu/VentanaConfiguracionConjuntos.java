    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String texto = txtElementosA.getText().trim();

            if (texto.isEmpty()) {
                throw new Exception("Por favor ingrese al menos un número para el conjunto.");
            }

            texto = texto.replace("{", "").replace("}", "").trim();
            String[] elementosStr = texto.split(",");

            ConjuntoEnVector vector = new ConjuntoEnVector();
            ConjuntoEnLista lista = new ConjuntoEnLista();

            for (String item : elementosStr) {
                String numLimpio = item.trim();
                if (!numLimpio.isEmpty()) {
                    int numero = Integer.parseInt(numLimpio);

                    // Validar pertenencia al Universo
                    if (!control.getUniversalActual().contiene(numero)) {
                        throw new Exception("El número " + numero + " no pertenece al Conjunto Universal.");
                    }

                    vector.agregar(numero);
                    lista.agregar(numero);
                }
            }

            if (guardandoA) {
                // Guardar A
                control.setConjuntoAVector(vector);
                control.setConjuntoALista(lista);

                JOptionPane.showMessageDialog(this,
                        "Conjunto A guardado con éxito (" + vector.getTamano() + " elementos).\nAhora ingrese los elementos del Conjunto B.",
                        "Éxito", JOptionPane.INFORMATION_MESSAGE);

                // Cambiar la interfaz para el Conjunto B
                guardandoA = false;
                lblElementosConjunto.setText("Ingrese los elementos del conjunto B:");
                txtElementosA.setText(""); // Limpiar el área de texto
                btnGuardar.setText("Guardar Conjunto B");

            } else {
                // Guardar B
                control.setConjuntoBVector(vector);
                control.setConjuntoBLista(lista);

                JOptionPane.showMessageDialog(this,
                        "Conjunto B guardado con éxito (" + vector.getTamano() + " elementos).",
                        "Éxito", JOptionPane.INFORMATION_MESSAGE);

                // 1. Crear la instancia de la ventana de operaciones pasando la controladora
                VentanaOperaciones ventanaOps = new VentanaOperaciones(control);

                // 2. Hacer visible la nueva ventana
                ventanaOps.setVisible(true);

                // 3. Cerrar/liberar la ventana actual de configuración
                this.dispose();
            }

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "Asegúrese de ingresar solo números enteros separados por comas.",
                    "Formato Incorrecto", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this,
                    ex.getMessage(),
                    "Error de Validación", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

